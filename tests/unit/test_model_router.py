@pytest.mark.tier2
@pytest.mark.asyncio
async def test_router_cascades_through_all_tiers_when_offline_not_set(monkeypatch, clean_pyspark_code: str):
    """Tier 2: When offline_mode=False but network is down, router records full cascade."""
    monkeypatch.setenv("MIDAS_OFFLINE_MODE", "0")
    router = DeterministicModelRouter(offline_mode=False)
    req = RefactoringRequest(
        file_path="jobs/clean.py",
        original_code=clean_pyspark_code,
        engine="glue",
        offline_only=False,
    )
    res = await router.route_and_optimize(req)

    assert res.tier_used == ModelTier.DETERMINISTIC_OFFLINE
    assert any("tier_1" in step for step in res.fallback_chain)
    assert any("tier_2" in step for step in res.fallback_chain)
    assert res.ast_valid is True


@pytest.mark.tier2
def test_pydantic_refactoring_models_serialization():
    """Tier 2: Refactoring request and response models serialize cleanly to dict and JSON."""
    res = RefactoringResponse(
        optimized_code="x = 1\n",
        diff="",
        explanation="Test explanation",
        tier_used=ModelTier.DETERMINISTIC_OFFLINE,
        provider_name="test-provider",
        fallback_chain=["offline"],
        ast_valid=True,
    )
    dumped = res.model_dump()
    assert dumped["tier_used"] == "deterministic_offline"
    assert dumped["ast_valid"] is True
