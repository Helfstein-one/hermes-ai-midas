"""Unit and boundary tests for the Multi-Tier Model Router and Deterministic Offline Fallback.

Tiers Covered:
- Tier 1: Feature Coverage (Tier 1 -> Tier 2 -> Tier 3 routing cascade, Deterministic Fallback)
- Tier 2: Boundary & Corner Cases (Timeout handling, Missing API keys, Offline flag bypass)
- Tier 3: Syntax and Bytecode Compilation Validation of router-generated code
"""

from __future__ import annotations

import pytest

# ============================================================================
# Router Contracts & Reference Specification
# ============================================================================
from hermes_midas.router import (
    DeterministicModelRouter,
    ModelTier,
    RefactoringRequest,
    RefactoringResponse,
)

# ============================================================================
# Tier 1: Feature Unit Tests
# ============================================================================


@pytest.mark.tier1
@pytest.mark.asyncio
async def test_router_falls_back_to_tier3_offline():
    """Tier 1: Router routes to Tier 3 Deterministic Fallback in offline mode."""
    code_with_bare_action = """from pyspark.sql import SparkSession
spark = SparkSession.builder.appName("Test").getOrCreate()
df = spark.read.parquet("s3://bucket/data/")
df.count()
df.write.parquet("s3://bucket/out/")
"""
    router = DeterministicModelRouter(offline_mode=True)
    req = RefactoringRequest(
        file_path="jobs/orders.py",
        original_code=code_with_bare_action,
        engine="glue",
        offline_only=True,
    )
    res = await router.route_and_optimize(req)

    assert res.tier_used == ModelTier.DETERMINISTIC_OFFLINE
    assert res.ast_valid is True
    assert "df.count()" not in res.optimized_code
    assert res.diff != ""


@pytest.mark.tier1
@pytest.mark.asyncio
async def test_router_generated_code_compiles(unbroadcasted_join_code: str):
    """Tier 1: Code generated by Tier 3 fallback compiles cleanly via compile(..., 'exec')."""
    router = DeterministicModelRouter(offline_mode=True)
    req = RefactoringRequest(
        file_path="jobs/attribution.py",
        original_code=unbroadcasted_join_code,
        engine="emr_serverless",
    )
    res = await router.route_and_optimize(req)

    assert res.ast_valid is True
    # Verify bytecode compilation
    compiled = compile(res.optimized_code, "<router_output>", "exec")
    assert compiled is not None


